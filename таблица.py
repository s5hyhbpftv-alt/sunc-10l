#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Расписание 10-Л одной таблицей на листе А4 — под чёрно-белый принтер.

Здесь нет ни цвета, ни заливок: на монохромной печати они превращаются в
грязный растр и съедают тонер. Предметы различаются весом шрифта и рамкой,
приёмы пищи — узкой полосой в разрыве сетки. Строки равной высоты: лист
вешают на стену и читают глазами, а не измеряют по нему время.

    python3 таблица.py
"""
import os, sys
from reportlab.pdfgen import canvas as rl
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.lib.colors import Color, HexColor
from reportlab.lib.units import mm

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ЗДЕСЬ)
from data import LESSON_TIMES, INTERVALS, WEEK, ТЕКСТЫ
from marks import draw_signet, draw_studio

ВЫХОД = os.path.join(ЗДЕСЬ, 'out', 'Расписание 10-Л — таблица.pdf')
ШРИФТЫ = os.path.join(ЗДЕСЬ, 'fonts')

Ш, В = 297 * mm, 210 * mm          # А4 поперёк
ПОЛЕ = 10 * mm
ЛЕВ, ПРАВ = ПОЛЕ, Ш - ПОЛЕ
ВЕРХ, НИЗ = В - ПОЛЕ, ПОЛЕ
ШИР = ПРАВ - ЛЕВ

ЧЁРНЫЙ = HexColor('#000000')
ТЁМНЫЙ = HexColor('#1A1A1A')
СЕРЫЙ  = HexColor('#666666')
СВЕТЛЫЙ = HexColor('#9A9A9A')
СЕТКА  = HexColor('#8C8C8C')
ФОН_ЕДЫ = HexColor('#EDEDED')

for имя, ф in [('Ж', 'Manrope-800.ttf'), ('П', 'Manrope-600.ttf'), ('О', 'Manrope-400.ttf'),
               ('М', 'JetBrainsMono-Regular.ttf'), ('МЖ', 'JetBrainsMono-Bold.ttf')]:
    pdfmetrics.registerFont(TTFont(имя, os.path.join(ШРИФТЫ, ф)))


def чч(m):
    return '%02d:%02d' % (m // 60, m % 60)


def разрядка(c, txt, x, y, шрифт, кегль, тр, цвет, вырав='l'):
    c.setFont(шрифт, кегль); c.setFillColor(цвет)
    ш = [pdfmetrics.stringWidth(з, шрифт, кегль) for з in txt]
    всего = sum(ш) + тр * max(0, len(txt) - 1)
    if вырав == 'c': x -= всего / 2.0
    elif вырав == 'r': x -= всего
    for з, w in zip(txt, ш):
        c.drawString(x, y, з); x += w + тр
    return всего


def ширина(txt, шрифт, кегль, тр=0):
    return sum(pdfmetrics.stringWidth(з, шрифт, кегль) for з in txt) + тр * max(0, len(txt) - 1)


def строки_по_ширине(txt, шрифт, кегль, место):
    слова, строки, тек = txt.split(), [], ''
    for w in слова:
        проба = (тек + ' ' + w).strip()
        if pdfmetrics.stringWidth(проба, шрифт, кегль) <= место:
            тек = проба
        else:
            if тек: строки.append(тек)
            тек = w
    if тек: строки.append(тек)
    return строки


def подогнать(c, txt, x, y, шрифт, кегль, место, цвет, вырав='c', мин=5.0):
    while кегль > мин and pdfmetrics.stringWidth(txt, шрифт, кегль) > место:
        кегль -= 0.2
    while pdfmetrics.stringWidth(txt, шрифт, кегль) > место and len(txt) > 4:
        txt = txt[:-2] + '…'
    разрядка(c, txt, x, y, шрифт, кегль, 0, цвет, вырав)


def еда_между():
    """Приёмы пищи, попадающие внутрь учебного дня, — по номеру урока, после
    которого они стоят."""
    из = {}
    for вид, имя, a, b in INTERVALS:
        if вид != 'meal':
            continue
        for n, (la, lb) in LESSON_TIMES.items():
            if lb <= a and n + 1 in LESSON_TIMES and LESSON_TIMES[n + 1][0] >= b:
                из[n] = (имя, a, b)
    return из


def главная():
    c = rl.Canvas(ВЫХОД, pagesize=(Ш, В))
    c.setTitle('Расписание 10-Л · СУНЦ МГУ · таблица на один лист')
    c.setAuthor('СУНЦ МГУ · internat.msu.ru')
    c.setSubject('Расписание 10-Л одной таблицей для чёрно-белой печати')

    # ── шапка ──────────────────────────────────────────────────────────────
    draw_signet(c, ЛЕВ + 9 * mm, ВЕРХ - 9 * mm, 9 * mm, 'Ж', mono='#000000')
    разрядка(c, '10-Л', ЛЕВ + 22 * mm, ВЕРХ - 8 * mm, 'Ж', 19, 0.5, ЧЁРНЫЙ)
    разрядка(c, 'ХИМИЧЕСКИЙ КЛАСС', ЛЕВ + 22 * mm, ВЕРХ - 12.6 * mm, 'П', 7, 2.4, СЕРЫЙ)
    разрядка(c, 'РАСПИСАНИЕ УРОКОВ · I СЕМЕСТР 2026/27 · КАБИНЕТ 40', ПРАВ,
             ВЕРХ - 8 * mm, 'П', 8, 2.0, ЧЁРНЫЙ, вырав='r')
    разрядка(c, 'СУНЦ МГУ · ШКОЛА-ИНТЕРНАТ ИМЕНИ А. Н. КОЛМОГОРОВА', ПРАВ,
             ВЕРХ - 12.6 * mm, 'О', 7, 1.4, СЕРЫЙ, вырав='r')

    # ── сетка ──────────────────────────────────────────────────────────────
    гутер = 20 * mm
    tx0 = ЛЕВ + гутер
    колw = (ПРАВ - tx0) / 6.0
    шапка_h = 7 * mm
    низ_блок = 20 * mm                       # место под сноски внизу
    верх_таб = ВЕРХ - 18 * mm
    еда = еда_между()
    полоса_еды = 4.8 * mm
    доступно = (верх_таб - шапка_h) - (НИЗ + низ_блок)
    строка = (доступно - len(еда) * полоса_еды) / 8.0

    # шапка таблицы
    разрядка(c, 'УРОК', ЛЕВ, верх_таб - 4.6 * mm, 'П', 7, 1.6, СЕРЫЙ)
    for i, день in enumerate(WEEK):
        cx = tx0 + i * колw
        разрядка(c, день[0].upper(), cx + колw / 2, верх_таб - 4.6 * mm, 'Ж', 9, 1.8,
                 ЧЁРНЫЙ, вырав='c')
    c.setStrokeColor(ЧЁРНЫЙ); c.setLineWidth(1.0)
    c.line(ЛЕВ, верх_таб - шапка_h, ПРАВ, верх_таб - шапка_h)

    # раскладка строк с учётом полос еды
    y = верх_таб - шапка_h
    ряд_y = {}
    for n in range(1, 9):
        ряд_y[n] = (y - строка, y)
        y -= строка
        if n in еда:
            имя, a, b = еда[n]
            c.setFillColor(ФОН_ЕДЫ)
            c.rect(ЛЕВ, y - полоса_еды, ШИР, полоса_еды, stroke=0, fill=1)
            основание = y - полоса_еды + 1.5 * mm
            разрядка(c, '%s—%s' % (чч(a), чч(b)), ЛЕВ + 1.5 * mm, основание, 'М', 6.2,
                     0.2, ТЁМНЫЙ)
            # название — у правого края: сдвоенные уроки перекрывают полосу слева,
            # а справа она свободна в обоих случаях
            разрядка(c, имя.upper(), ПРАВ - 2 * mm, основание, 'П', 6.4, 1.6, ТЁМНЫЙ,
                     вырав='r')
            y -= полоса_еды
    низ_таб = y

    # колонка времени
    for n in range(1, 9):
        yb, yt = ряд_y[n]
        a, b = LESSON_TIMES[n]
        разрядка(c, str(n), ЛЕВ + 1.5 * mm, (yb + yt) / 2 - 3.4, 'Ж', 11, 0, ЧЁРНЫЙ)
        разрядка(c, чч(a), ЛЕВ + 7 * mm, (yb + yt) / 2 + 0.6, 'МЖ', 7.2, 0.3, ТЁМНЫЙ)
        разрядка(c, чч(b), ЛЕВ + 7 * mm, (yb + yt) / 2 - 6.4, 'М', 7.2, 0.3, СЕРЫЙ)

    # линии сетки
    c.setStrokeColor(СЕТКА); c.setLineWidth(0.7)
    for n in range(1, 9):
        yb, _ = ряд_y[n]
        c.line(ЛЕВ, yb, ПРАВ, yb)
    for i in range(7):
        x = tx0 + i * колw
        c.line(x, верх_таб - шапка_h, x, низ_таб)
    c.setStrokeColor(ЧЁРНЫЙ); c.setLineWidth(1.0)
    c.line(ЛЕВ, низ_таб, ПРАВ, низ_таб)
    c.line(tx0, верх_таб - шапка_h, tx0, низ_таб)

    # ── уроки ──────────────────────────────────────────────────────────────
    for i, день in enumerate(WEEK):
        cx = tx0 + i * колw
        for l0, l1, сем, имя, зам, уч, каб in день[2]:
            yt = ряд_y[l0][1]
            yb = ряд_y[l1][0]
            c.setStrokeColor(ЧЁРНЫЙ); c.setLineWidth(0.9)
            c.rect(cx + 1.1 * mm, yb + 1.1 * mm, колw - 2.2 * mm, yt - yb - 2.2 * mm,
                   stroke=1, fill=0)
            место = колw - 6 * mm
            кегль = 9
            строки = строки_по_ширине(имя, 'Ж', кегль, место)
            while len(строки) > 2 and кегль > 6.6:
                кегль -= 0.4
                строки = строки_по_ширине(имя, 'Ж', кегль, место)
            высота_текста = len(строки) * кегль * 1.15
            есть_низ = bool(уч or каб)
            yy = (yb + yt) / 2 + высота_текста / 2 - кегль * 0.86 + (2.2 * mm if есть_низ else 0)
            for с in строки:
                подогнать(c, с, cx + колw / 2, yy, 'Ж', кегль, место, ЧЁРНЫЙ)
                yy -= кегль * 1.15
            if уч:
                подогнать(c, уч, cx + колw / 2, yy - 0.4 * mm, 'О', 6.4, место, СЕРЫЙ)
                yy -= 3.2 * mm
            if каб:
                подогнать(c, 'каб. ' + каб, cx + колw / 2, yy - 0.4 * mm, 'М', 6.6,
                          место, ТЁМНЫЙ)
            if зам:
                разрядка(c, зам.upper(), cx + колw / 2, yt - 4.2 * mm, 'О', 5.6, 1.2,
                         СВЕТЛЫЙ, вырав='c')

    # ── сноски ─────────────────────────────────────────────────────────────
    y = НИЗ + 14 * mm
    вне = [(и, a, b) for вид, и, a, b in INTERVALS
           if вид == 'meal' and (b <= LESSON_TIMES[1][0] or a >= LESSON_TIMES[8][1] - 5)]
    x = ЛЕВ
    x += разрядка(c, 'ВНЕ СЕТКИ УРОКОВ', x, y, 'П', 6.6, 2.0, СЕРЫЙ) + 6 * mm
    for и, a, b in вне:
        x += разрядка(c, и.upper(), x, y, 'П', 6.6, 1.4, ТЁМНЫЙ) + 2.5 * mm
        x += разрядка(c, '%s — %s' % (чч(a), чч(b)), x, y, 'М', 6.6, 0.4, ЧЁРНЫЙ) + 7 * mm
    разрядка(c, 'ПЕРЕМЕНЫ ПО 10 МИНУТ', x, y, 'О', 6.6, 1.4, СЕРЫЙ)

    c.setStrokeColor(СЕТКА); c.setLineWidth(0.5)
    c.line(ЛЕВ, НИЗ + 9 * mm, ПРАВ, НИЗ + 9 * mm)
    разрядка(c, 'ДАННЫЕ: INTERNAT.MSU.RU · РАСПИСАНИЕ УЧЕБНЫХ ЗАНЯТИЙ НА I СЕМЕСТР 2026/27',
             ЛЕВ, НИЗ + 4 * mm, 'О', 6.2, 1.2, СВЕТЛЫЙ)
    draw_studio(c, ТЕКСТЫ['студия'].upper(), ПРАВ, НИЗ + 4 * mm, 'П', 6.6, 1.8,
                СЕРЫЙ, ЧЁРНЫЙ, вырав='r')

    c.showPage(); c.save()
    print('ОК →', ВЫХОД, os.path.getsize(ВЫХОД), 'байт')


if __name__ == '__main__':
    главная()
