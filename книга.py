def абзац(c, txt, x, y, место, шрифт, кегль, шаг, цвет):
    """Простая заливка абзаца в заданную ширину. Возвращает нижнюю границу."""
    from reportlab.pdfbase import pdfmetrics as _pm
    слова, строка = txt.split(), ''
    for w in слова:
        проба = (строка + ' ' + w).strip()
        if _pm.stringWidth(проба, шрифт, кегль) <= место:
            строка = проба
        else:
            разрядка(c, строка, x, y, шрифт, кегль, 0, цвет)
            y -= шаг
            строка = w
    if строка:
        разрядка(c, строка, x, y, шрифт, кегль, 0, цвет)
        y -= шаг
    return y


def полосы_дня(день):
    return [(LESSON_TIMES[a][0], LESSON_TIMES[b][1], сем, имя, зам, уч, каб, a, b)
            for a, b, сем, имя, зам, уч, каб in день[2]]


def счёт(день):
    б = полосы_дня(день)
    n = sum(x[8] - x[7] + 1 for x in б)
    return n, n * 45, б[0][0], б[-1][1]


def трапезы():
    из = []
    for вид, имя, a, b in INTERVALS:
        if вид != 'meal': continue
        a2, b2 = max(a, НАЧАЛО), min(b, КОНЕЦ)
        if b2 - a2 >= 10: из.append((имя, a2, b2))
    return из


def подогнать(c, txt, x, y, шрифт, кегль, место, цвет, вырав='c', мин=5.0):
    """Ужимает строку до места, в крайнем случае обрезает многоточием."""
    while кегль > мин and pdfmetrics.stringWidth(txt, шрифт, кегль) > место:
        кегль -= 0.2
    while pdfmetrics.stringWidth(txt, шрифт, кегль) > место and len(txt) > 5:
        txt = txt[:-2] + '…'
    разрядка(c, txt, x, y, шрифт, кегль, 0.2, цвет, вырав)


def склон(n):
    return 'урока' if n in (2, 3, 4) else 'уроков'


# ── Спектр недели ───────────────────────────────────────────────────────────
def спектр(c, x, y, w, h, активный=None, зазор=None, часы=False, подписи=False):
    зазор = зазор if зазор is not None else 2.2 * mm
    кол = w / 6.0
    if часы:
        for ч in range(9, 17):
            yy = y + h - (ч * 60 - НАЧАЛО) / ДЛИНА * h
            разрядка(c, '%02d' % ч, x - 2.4 * mm, yy - 2, 'Mono', 6.4, 0.6, ТЕНЬ, вырав='r')
    for i, день in enumerate(WEEK):
        cx = x + i * кол
        свой = (активный is None) or (i == активный)
        c.setFillColor(ПАНЕЛЬ if свой else смешать(ЧЕРНИЛА, ПАНЕЛЬ, 0.55))
        c.rect(cx, y, кол - зазор, h, stroke=0, fill=1)
        for ч in range(9, 17):
            yy = y + h - (ч * 60 - НАЧАЛО) / ДЛИНА * h
            волос(c, cx, yy, cx + кол - зазор, смешать(ЧЕРНИЛА, БУМАГА, 0.07), 0.35)
        for (m0, m1, сем, *_) in полосы_дня(день):
            by = y + h - (m1 - НАЧАЛО) / ДЛИНА * h
            bh = (m1 - m0) / ДЛИНА * h
            цв = HexColor(FAMILY[сем][0])
            c.setFillColor(цв if свой else смешать(ЧЕРНИЛА, цв, 0.36))
            c.rect(cx, by, кол - зазор, bh, stroke=0, fill=1)
        разрядка(c, день[1].upper(), cx + (кол - зазор) / 2, y + h + 3 * mm,
                 'MonoBold' if свой else 'Mono', 6.4, 1.4,
                 БУМАГА if свой else ТЕНЬ, вырав='c')
        if подписи:
            n = sum(b[1] - b[0] + 1 for b in день[2])
            разрядка(c, день[0].upper(), cx + (кол - зазор) / 2, y - 5 * mm, 'Mono',
                     6.4, 1.8, ТУСКЛЫЙ, вырав='c')
            разрядка(c, '%d %s' % (n, склон(n).upper()), cx + (кол - зазор) / 2,
                     y - 9 * mm, 'Mono', 5.8, 1.4, ТЕНЬ, вырав='c')


