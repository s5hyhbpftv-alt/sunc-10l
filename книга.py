# ── Примитивы ───────────────────────────────────────────────────────────────
def смешать(a, b, t):
    return Color(a.red + (b.red - a.red) * t, a.green + (b.green - a.green) * t,
                 a.blue + (b.blue - a.blue) * t)


def чч(m):
    return '%02d:%02d' % (m // 60, m % 60)


def разрядка(c, txt, x, y, шрифт, кегль, тр, цвет, вырав='l'):
    """Строка с разрядкой. Tc не трогаем: сдвигаем каждый знак руками."""
    c.setFont(шрифт, кегль); c.setFillColor(цвет)
    ш = [pdfmetrics.stringWidth(з, шрифт, кегль) for з in txt]
    всего = sum(ш) + тр * max(0, len(txt) - 1)
    if вырав == 'c': x -= всего / 2.0
    elif вырав == 'r': x -= всего
    for з, w in zip(txt, ш):
        c.drawString(x, y, з); x += w + тр
    return всего


def ширина(txt, шрифт, кегль, тр):
    return sum(pdfmetrics.stringWidth(з, шрифт, кегль) for з in txt) + тр * max(0, len(txt) - 1)


def фон(c):
    c.setFillColor(ЧЕРНИЛА); c.rect(0, 0, Ш, В, stroke=0, fill=1)


def волос(c, x1, y, x2, цвет=ЛИНИЯ, w=0.5):
    c.setStrokeColor(цвет); c.setLineWidth(w); c.line(x1, y, x2, y)


