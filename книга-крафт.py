def абзац(c, txt, x, y, место, шрифт, кегль, шаг, цвет):
    """Простая заливка абзаца в заданную ширину. Возвращает нижнюю границу."""
    слова, строка = txt.split(), ''
    for w in слова:
        проба = (строка + ' ' + w).strip()
        if pdfmetrics.stringWidth(проба, шрифт, кегль) <= место:
            строка = проба
        else:
            разрядка(c, строка, x, y, шрифт, кегль, 0, цвет)
            y -= шаг
            строка = w
    if строка:
        разрядка(c, строка, x, y, шрифт, кегль, 0, цвет)
        y -= шаг
    return y


def полосы_дня(день):
    return [(LESSON_TIMES[a][0], LESSON_TIMES[b][1], сем, имя, зам, уч, каб, a, b)
            for a, b, сем, имя, зам, уч, каб in день[2]]


def счёт(день):
    б = полосы_дня(день)
    n = sum(x[8] - x[7] + 1 for x in б)
    return n, n * 45, б[0][0], б[-1][1]


def трапезы():
    из = []
    for вид, имя, a, b in INTERVALS:
        if вид != 'meal': continue
        a2, b2 = max(a, НАЧАЛО), min(b, КОНЕЦ)
        if b2 - a2 >= 10: из.append((имя, a2, b2))
    return из


def склон(n):
    return 'урока' if n in (2, 3, 4) else 'уроков'


def свод_предметов():
    свод = {}
    for д in WEEK:
        for a, b, сем, *_ in д[2]:
            свод[сем] = свод.get(сем, 0) + (b - a + 1)
    return sorted(свод.items(), key=lambda kv: (-kv[1], FAMILY[kv[0]][1]))


# ── Спектр недели ───────────────────────────────────────────────────────────
def спектр(c, x, y, w, h, активный=None, зазор=None, часы=False, подписи=False):
    зазор = зазор if зазор is not None else 2.2 * mm
    кол = w / 6.0
    if часы:
        for ч in range(9, 17):
            yy = y + h - (ч * 60 - НАЧАЛО) / ДЛИНА * h
            разрядка(c, '%02d' % ч, x - 2.4 * mm, yy - 2, 'Маш', 6.4, 0.6, БЛЕДНЫЙ, вырав='r')
    for i, день in enumerate(WEEK):
        cx = x + i * кол
        свой = (активный is None) or (i == активный)
        c.setFillColor(смешать(КРАФТ, ЧЕРНИЛА, 0.07))
        c.rect(cx, y, кол - зазор, h, stroke=0, fill=1)
        c.setStrokeColor(смешать(КРАФТ, ЧЕРНИЛА, 0.22)); c.setLineWidth(0.4)
        c.rect(cx, y, кол - зазор, h, stroke=1, fill=0)
        for (m0, m1, сем, *_) in полосы_дня(день):
            by = y + h - (m1 - НАЧАЛО) / ДЛИНА * h
            bh = (m1 - m0) / ДЛИНА * h
            цв = HexColor(КРАСКА[сем])
            c.setFillColor(цв if свой else смешать(КРАФТ, цв, 0.34))
            c.rect(cx, by, кол - зазор, bh, stroke=0, fill=1)
        разрядка(c, день[1].upper(), cx + (кол - зазор) / 2, y + h + 3 * mm,
                 'МашЖ' if свой else 'Маш', 6.4, 1.4,
                 ЧЕРНИЛА if свой else БЛЕДНЫЙ, вырав='c')
        if подписи:
            n = sum(b[1] - b[0] + 1 for b in день[2])
            разрядка(c, день[0].upper(), cx + (кол - зазор) / 2, y - 5 * mm, 'Маш',
                     6.4, 1.8, ПОЛУТОН, вырав='c')
            разрядка(c, '%d %s' % (n, склон(n).upper()), cx + (кол - зазор) / 2,
                     y - 9 * mm, 'Маш', 5.8, 1.4, БЛЕДНЫЙ, вырав='c')


