def волос(c, x1, y, x2, цвет=None, w=0.5):
    c.setStrokeColor(цвет or смешать(КРАФТ, ЧЕРНИЛА, 0.30))
    c.setLineWidth(w); c.line(x1, y, x2, y)


def сетка(c, x, y, w, h, шаг=5 * mm, сила=0.10):
    """Миллиметровка под лентой дня — как разлиновка журнала."""
    c.saveState(); c.setStrokeColor(смешать(КРАФТ, ЧЕРНИЛА, сила)); c.setLineWidth(0.28)
    i = 0
    while x + i * шаг <= x + w + 0.1:
        c.line(x + i * шаг, y, x + i * шаг, y + h); i += 1
    i = 0
    while y + i * шаг <= y + h + 0.1:
        c.line(x, y + i * шаг, x + w, y + i * шаг); i += 1
    c.restoreState()


def кольцо_стакана(c, cx, cy, r, сила=0.16):
    """След от донышка: два обода и лёгкая заливка внутри."""
    c.saveState()
    c.setFillColor(смешать(КРАФТ, ЧЕРНИЛА, сила * 0.30)); c.setStrokeColor(смешать(КРАФТ, ЧЕРНИЛА, сила))
    c.circle(cx, cy, r, stroke=0, fill=1)
    c.setLineWidth(1.7); c.circle(cx, cy, r, stroke=1, fill=0)
    c.setLineWidth(0.7); c.circle(cx, cy, r - 1.6 * mm, stroke=1, fill=0)
    c.restoreState()


def штамп(c, cx, cy, угол, строки, ш=54 * mm, в=20 * mm):
    """Оттиск: двойная рамка и машинописные строки, слегка вкось."""
    c.saveState(); c.translate(cx, cy); c.rotate(угол)
    c.setStrokeColor(ШТЕМПЕЛЬ); c.setFillColor(ШТЕМПЕЛЬ)
    c.setLineWidth(1.5); c.roundRect(-ш / 2, -в / 2, ш, в, 2 * mm, stroke=1, fill=0)
    c.setLineWidth(0.5); c.roundRect(-ш / 2 + 1.4 * mm, -в / 2 + 1.4 * mm,
                                     ш - 2.8 * mm, в - 2.8 * mm, 1.4 * mm, stroke=1, fill=0)
    y = в / 2 - 6.4 * mm
    for i, с in enumerate(строки):
        разрядка(c, с, 0, y, 'МашЖ' if i == 0 else 'Маш', 8 if i == 0 else 6.4,
                 2.2 if i == 0 else 1.6, ШТЕМПЕЛЬ, вырав='c')
        y -= 5.2 * mm
    c.restoreState()


def этикетка(c, x, y, w, h):
    """Наклеенная этикетка реактива: чуть светлее бумаги, тонкая рамка."""
    c.setFillColor(smix_light()); c.rect(x, y, w, h, stroke=0, fill=1)
    c.setStrokeColor(смешать(КРАФТ, ЧЕРНИЛА, 0.34)); c.setLineWidth(0.7)
    c.rect(x, y, w, h, stroke=1, fill=0)
    c.setStrokeColor(смешать(КРАФТ, ЧЕРНИЛА, 0.20)); c.setLineWidth(0.4)
    c.rect(x + 1.6 * mm, y + 1.6 * mm, w - 3.2 * mm, h - 3.2 * mm, stroke=1, fill=0)


def smix_light():
    return Color(0.902, 0.845, 0.744)


