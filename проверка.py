# -*- coding: utf-8 -*-
"""Сверка `data.py` с заводским файлом интерната и проверка внутренней логики.

Колонка 10-Л разбирается заново — по рамкам ячеек, как в первый раз, — и
результат сравнивается с тем, что лежит в `data.py`. Так смена семестра
не пройдёт молча: если файл обновится, а данные нет, проверка это скажет.

    python3 проверка.py
"""
import os, sys, re
import openpyxl

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ЗДЕСЬ)
from data import LESSON_TIMES, INTERVALS, FAMILY, WEEK, ЭПИГРАФ, ТЕКСТЫ

ИСТОЧНИК = os.path.join(ЗДЕСЬ, 'source-1-semestr-26-27.xlsx')
КОЛОНКА = 8                       # H — 10-Л
ДНИ = [('Понедельник', 10, 25), ('Вторник', 26, 45), ('Среда', 46, 65),
       ('Четверг', 66, 81), ('Пятница', 82, 97), ('Суббота', 98, 113)]

ошибки, замечания = [], []


def сказать(список, текст):
    список.append(текст)


# ── разбор источника ────────────────────────────────────────────────────────
def разобрать():
    wb = openpyxl.load_workbook(ИСТОЧНИК)
    ws = wb['Лист1']
    # горизонтальные слияния: значение живёт в левой ячейке
    слияния = {}
    for rng in ws.merged_cells.ranges:
        for r in range(rng.min_row, rng.max_row + 1):
            for c in range(rng.min_col, rng.max_col + 1):
                слияния[(r, c)] = (rng.min_row, rng.min_col)

    def значение(r, c):
        rr, cc = слияния.get((r, c), (r, c))
        v = ws.cell(rr, cc).value
        return str(v).strip() if v is not None else ''

    из_файла = {}
    for имя, начало, конец in ДНИ:
        # слоты: номер урока стоит в колонке B на первой строке слота
        слоты = {}
        for r in range(начало, конец + 1):
            b = ws.cell(r, 2).value
            if isinstance(b, int) and 1 <= b <= 8:
                слоты[b] = r
        # Граница блока задаётся либо нижней рамкой строки, либо верхней рамкой
        # следующей: в исходнике встречаются оба способа.
        конец_блока = set()
        for r in range(начало, конец + 1):
            низ = ws.cell(r, КОЛОНКА).border.bottom.style
            верх_ниже = ws.cell(r + 1, КОЛОНКА).border.top.style if r < конец else None
            if низ or верх_ниже:
                конец_блока.add(r)
        блоки, текущий = [], None
        for n in sorted(слоты):
            r = слоты[n]
            занят = any(значение(rr, КОЛОНКА) for rr in (r, r + 1))
            if текущий is None:
                текущий = [n, n, занят]
            else:
                текущий[1] = n
                текущий[2] = текущий[2] or занят
            if r in конец_блока or (r + 1) in конец_блока:
                if текущий[2]:
                    блоки.append((текущий[0], текущий[1]))
                текущий = None
        if текущий and текущий[2]:
            блоки.append((текущий[0], текущий[1]))
        из_файла[имя] = блоки
    return из_файла, значение, слоты


def сверить_расписание():
    из_файла, значение, _ = разобрать()
    for (имя, начало, конец), день in zip(ДНИ, WEEK):
        свои = [(b[0], b[1]) for b in день[2]]
        чужие = из_файла[имя]
        if свои != чужие:
            сказать(ошибки, '%s: блоки разошлись. в data.py %s, в файле %s'
                    % (имя, свои, чужие))


def проверить_звонки():
    пары = sorted(LESSON_TIMES.items())
    for n, (a, b) in пары:
        if b - a != 45:
            сказать(ошибки, 'урок %d длится %d мин вместо 45' % (n, b - a))
    for (n1, (a1, b1)), (n2, (a2, b2)) in zip(пары, пары[1:]):
        if a2 < b1:
            сказать(ошибки, 'уроки %d и %d накладываются' % (n1, n2))
        if a2 - b1 < 5:
            сказать(замечания, 'между уроками %d и %d всего %d мин' % (n1, n2, a2 - b1))
    for вид, имя, a, b in INTERVALS:
        if b <= a:
            сказать(ошибки, 'интервал «%s» кончается раньше, чем начинается' % имя)


def проверить_целостность():
    всего = 0
    for день in WEEK:
        занято = set()
        for l0, l1, сем, имя, зам, уч, каб in день[2]:
            if l0 > l1:
                сказать(ошибки, '%s: блок %s—%s задом наперёд' % (день[0], l0, l1))
            пересечение = занято & set(range(l0, l1 + 1))
            if пересечение:
                сказать(ошибки, '%s: слоты %s заняты дважды' % (день[0], sorted(пересечение)))
            занято |= set(range(l0, l1 + 1))
            if сем not in FAMILY:
                сказать(ошибки, '%s: неизвестный предмет «%s»' % (день[0], сем))
            if not имя:
                сказать(ошибки, '%s: блок без названия' % день[0])
            всего += l1 - l0 + 1
    if всего != 38:
        сказать(ошибки, 'всего уроков %d, а в текстах указано 38' % всего)
    if len(ЭПИГРАФ) != len(WEEK):
        сказать(ошибки, 'эпиграфов %d на %d дней' % (len(ЭПИГРАФ), len(WEEK)))
    for i, э in enumerate(ЭПИГРАФ):
        if not э.strip().endswith(('.', '!', '?')):
            сказать(замечания, 'эпиграф %d не заканчивается точкой' % (i + 1))
    for ключ in ('девиз', 'обложка', 'ключ', 'хронометраж', 'хроматограмма', 'состав', 'студия'):
        if ключ not in ТЕКСТЫ:
            сказать(ошибки, 'в ТЕКСТАХ нет ключа «%s»' % ключ)


def проверить_вывод():
    из_pdf = {}
    for имя, полос in [('Расписание 10-Л — СУНЦ МГУ.pdf', 12),
                       ('Расписание 10-Л — крафт.pdf', 12),
                       ('v1-raspisanie-10L-SUNC-MGU.pdf', 10)]:
        путь = os.path.join(ЗДЕСЬ, 'out', имя)
        if not os.path.exists(путь):
            сказать(ошибки, 'нет файла %s' % имя); continue
        текст = os.popen('pdftotext "%s" - 2>/dev/null' % путь).read()
        страниц = текст.count('\f')
        if страниц != полос:
            сказать(ошибки, '%s: полос %d вместо %d' % (имя, страниц, полос))
        # pdftotext отдаёт слова в порядке рисования, а не чтения, поэтому
        # ищем каждое слово подписи отдельно, а не строку целиком
        плотно = re.sub(r'\s+', '', текст).upper()
        верх = текст.upper()
        нет = [w for w in ('РАЗРАБОТАНО', 'NASTENA', 'CREATIVE', 'STUDIO') if w not in верх]
        if нет:
            сказать(ошибки, '%s: в подписи студии не хватает %s' % (имя, ', '.join(нет)))
        for слово in ('ХРОНОМЕТРАЖ', 'ХРОМАТОГРАММА', 'СОСТАВ'):
            if слово not in плотно:
                сказать(ошибки, '%s: нет раздела «%s»' % (имя, слово))
        из_pdf[имя] = текст
    return из_pdf


def главная():
    сверить_расписание()
    проверить_звонки()
    проверить_целостность()
    проверить_вывод()
    print('Ошибки:', len(ошибки))
    for o in ошибки: print('  ✗', o)
    print('Замечания:', len(замечания))
    for z in замечания: print('  ·', z)
    return 1 if ошибки else 0


if __name__ == '__main__':
    sys.exit(главная())
